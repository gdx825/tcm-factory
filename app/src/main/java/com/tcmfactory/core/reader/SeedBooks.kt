            辨少阳病脉证并治

            263．少阳之为病，口苦，咽干，目眩也。

            264．少阳中风，两耳无所闻，目赤，胸中满而烦者，不可吐下，吐下则悸而惊。

            265．伤寒，脉弦细，头痛发热者，属少阳。少阳不可发汗，发汗则谵语，此属胃。胃和则愈，胃不和，烦而悸。

            266．本太阳病不解，转入少阳者，胁下硬满，干呕不能食，往来寒热，尚未吐下，脉沉紧者，与小柴胡汤。

